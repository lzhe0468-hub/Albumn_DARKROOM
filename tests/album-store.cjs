const { AlbumStore } = require('../album-store');
const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const directory = fs.mkdtempSync(path.join(__dirname, '.store-'));
const store = new AlbumStore(directory);
assert.equal(store.read().data,null);
const data={version:1,nextId:2,selectedIdx:0,rolls:[{id:1,name:'中文',active:true,shots:[{src:'data:image/png;base64,aGVsbG8=',title:'照片',rating:4.5}]}]};
const saved=store.write(data);
assert.equal(fs.readdirSync(store.photos).length,1);
assert.ok(saved.rolls[0].shots[0].src.startsWith('file:'));
assert.equal(JSON.parse(fs.readFileSync(store.file)).rolls[0].shots[0].src,'');
saved.rolls[0].name='修改';store.write(saved);
assert.equal(new AlbumStore(directory).read().data.rolls[0].name,'修改');
fs.writeFileSync(store.file,'broken');
assert.ok(store.read().warning);
assert.equal(store.read().data.rolls[0].name,'中文');
store.write(store.read().data);
assert.ok(fs.readdirSync(directory).some(f=>f.includes('.corrupt-')));
const original=store.atomicWrite;
store.atomicWrite=()=>{throw Object.assign(new Error('disk full'),{code:'ENOSPC'})};
assert.throws(()=>store.write(saved),/disk full/);
store.atomicWrite=original;
assert.equal(store.read().data.rolls[0].name,'中文');
assert.throws(()=>store.write({...saved,nextId:1}),/编号/);
const bad=structuredClone(saved);bad.rolls[0].shots[0].photoFile='../bad.png';
assert.throws(()=>store.write(bad),/路径/);
console.log('PASS: photo externalization, restart, backup recovery, corrupt preservation, disk failure, validation');
