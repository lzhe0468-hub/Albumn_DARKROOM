const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {LibraryManager,MARKER}=require('../library-manager');
const root=fs.mkdtempSync(path.join(__dirname,'.store-library-'));
const inside=p=>{const r=path.relative(root,path.resolve(p));assert.ok(r && !r.startsWith('..')&&!path.isAbsolute(r));};
async function main(){
  const manager=new LibraryManager(path.join(root,'settings'));
  const original=manager.directory;
  assert.ok(manager.info().available);
  const album=manager.albumStore().write({version:1,nextId:2,selectedIdx:0,rolls:[{id:1,name:'本地双人相册',active:true,shots:[{src:'data:image/png;base64,aGVsbG8=',title:'原图',rating:4.5}]}]});
  manager.documentStore('journal').write({version:1,notes:'随笔\n两个人用一台设备',nextGoalId:2,goals:[{id:1,name:'拍摄计划',desc:'中文构想',cur:0,tgt:36,frames:[]}]});
  manager.documentStore('people').write({version:1,a:'甲',b:'乙'});
  manager.documentStore('wishlist').write({version:1,nextRollId:2,rolls:[{id:1,name:'心愿',total:1,frames:[{letters:{a:'甲的信',b:'乙的信'},src:null}]}]});
  manager.documentStore('calendar').write({version:1,state:{'2026-10-17':{a:{shots:[{note:'记事'}]},b:{shots:[]}}}});
  const before=fs.readFileSync(path.join(original,'album.json'));
  const parent=path.join(root,'指定位置 有中文');fs.mkdirSync(parent);
  const moved=await manager.migrate(parent);
  assert.equal(moved.previousDirectory,original);
  assert.equal(moved.busy,false);
  assert.deepEqual(fs.readFileSync(path.join(original,'album.json')),before);
  assert.equal(manager.directory,path.join(parent,'DARKROOM照片库'));
  assert.ok(fs.existsSync(path.join(manager.directory,MARKER)));
  const restarted=new LibraryManager(path.join(root,'settings'));
  assert.equal(restarted.directory,manager.directory);
  assert.equal(restarted.documentStore('journal').read().data.notes,'随笔\n两个人用一台设备');
  assert.equal(restarted.documentStore('wishlist').read().data.rolls[0].frames[0].letters.b,'乙的信');
  const restored=restarted.albumStore().read().data.rolls[0].shots[0];
  assert.equal(restored.photoFile,album.rolls[0].shots[0].photoFile);
  assert.ok(restored.src.includes(encodeURIComponent('指定位置 有中文')));
  await assert.rejects(()=>restarted.migrate(restarted.directory),/内部/);
  const usedParent=path.join(root,'不能覆盖');fs.mkdirSync(path.join(usedParent,'DARKROOM照片库'),{recursive:true});
  fs.writeFileSync(path.join(usedParent,'DARKROOM照片库','sentinel'),'retain');
  await assert.rejects(()=>restarted.migrate(usedParent),/不会覆盖/);
  assert.equal(fs.readFileSync(path.join(usedParent,'DARKROOM照片库','sentinel'),'utf8'),'retain');
  const empty=path.join(root,'空目录');fs.mkdirSync(empty);
  await assert.rejects(()=>restarted.open(empty),/完整/);
  assert.equal(fs.readdirSync(empty).length,0);
  const failedParent=path.join(root,'校验失败');fs.mkdirSync(failedParent);
  const originalDigest=restarted.digest;let count=0;
  restarted.digest=async()=>String(count++);
  await assert.rejects(()=>restarted.migrate(failedParent),/校验失败/);
  restarted.digest=originalDigest;
  assert.equal(new LibraryManager(path.join(root,'settings')).directory,manager.directory);
  assert.equal(fs.existsSync(path.join(failedParent,'DARKROOM照片库')),false);
  const offline=manager.directory+'.offline';inside(offline);inside(manager.directory);
  fs.renameSync(manager.directory,offline);
  const missing=new LibraryManager(path.join(root,'settings'));
  assert.equal(missing.info().available,false);
  assert.throws(()=>missing.albumStore(),/不可用/);
  assert.equal(fs.existsSync(manager.directory),false);
  fs.renameSync(offline,manager.directory);
  fs.writeFileSync(restarted.config,'broken');fs.writeFileSync(restarted.config+'.bak','broken');
  const broken=new LibraryManager(path.join(root,'settings'));
  assert.equal(broken.info().available,false);
  assert.match(broken.info().error,/设置损坏/);
  await broken.open(manager.directory);
  assert.equal(new LibraryManager(path.join(root,'settings')).directory,manager.directory);
  console.log('PASS: full library migration, file verification, originals retained, restart location, existing-library open, overwrite/nesting prevention, failed copy, offline storage and corrupt config recovery');
}
main().catch(error=>{console.error(error);process.exitCode=1});
